"""AI image generation (FW-071) through formvis, and the round trip to formvis for editing.

formvis owns generation: its catalogue (GET /api/generate) lists the generators the person has set up, local ones
(Krea 2, FLUX.2 [klein], ONNX diffusion; no key) and cloud ones (fal and the others, each with the person's own key).
FormWeb starts a job (POST /api/generate), follows it (GET /api/jobs/{id}) and, when it is done, copies each picture
into its own assets with provenance (prompt, generator, model licence, time) before telling formvis to forget its copy.
Nothing is generated by FormWeb itself, and no key ever passes through it.

Edit in formvis opens an image element's picture in the formvis window through formvis's MCP open_file tool (the
window must be open, and formvis asks the person once to allow outside agents). Update from formvis exports the
document the window shows (export_image) and makes it the element's new picture in one undo step, keeping the credit.
"""
import json
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

from .assets import ASSET_REF, asset_path, ingest, own_asset, visible_assets
from .background import FORMVIS_URL, START_HINT, _call
from .config import DATA_DIR
from .engine import EngineError


def _json(path: str, body: dict | None = None, timeout: float = 10.0) -> dict:
    data = None if body is None else json.dumps(body).encode()
    try:
        raw, _ = _call(path, data, {'Content-Type': 'application/json'} if data else None, timeout)
    except urllib.error.HTTPError as error:
        detail = error.read().decode('utf-8', 'replace')
        try:
            detail = json.loads(detail).get('detail', detail)
        except ValueError:
            pass
        raise EngineError(f'formvis: {detail}', 409 if error.code in (409, 428) else 404 if error.code == 404 else 502) from error
    except (urllib.error.URLError, OSError) as error:
        raise EngineError(f'formvis is not reachable at {FORMVIS_URL}. {START_HINT}', 503) from error
    return json.loads(raw) if raw else {}


def generators(studio) -> dict:
    studio.access.authorize('read')
    try:
        listed = _json('/api/generate', timeout=3.0).get('generators', [])
    except EngineError as error:
        return {'available': False, 'generators': [], 'note': str(error)}
    images = [{'id': g['id'], 'label': g.get('label', g['id']), 'provider': g.get('providerLabel') or g.get('provider'), 'local': g.get('provider') == 'local',
               'ready': bool(g.get('ready')), 'reason': g.get('reason') or ('' if g.get('ready') else f'Add a {g.get("providerLabel") or g.get("provider")} key in formvis Settings.'),
               'sizes': g.get('sizes') or [], 'licence': g.get('licence') or ''} for g in listed if g.get('kind') == 'image']
    ready = [g for g in images if g['ready']]
    note = (f'{len(ready)} of {len(images)} formvis generators are ready.' if ready else
            'formvis is running, but no image generator is set up: install a local model or add a provider key in formvis.')
    return {'available': bool(ready), 'generators': images, 'note': note}


def start(studio, prompt: str, generator: str | None = None, size: str | None = None, count: int = 1) -> dict:
    studio.access.authorize('edit')
    prompt = (prompt or '').strip()
    if not 3 <= len(prompt) <= 2000:
        raise EngineError('Describe the picture in 3 to 2,000 characters.')
    listing = generators(studio)
    ready = [g for g in listing['generators'] if g['ready']]
    if not ready:
        raise EngineError(listing['note'], 409 if listing['generators'] else 503)
    chosen = next((g for g in ready if g['id'] == generator), None) if generator else (next((g for g in ready if g['local']), None) or ready[0])
    if not chosen:
        raise EngineError(f'Generator {generator} is not ready in formvis. Ready: {", ".join(g["id"] for g in ready)}.', 409)
    if size and (chosen['sizes'] and size not in chosen['sizes']):
        raise EngineError(f'{chosen["label"]} offers {", ".join(chosen["sizes"])}.')
    count = max(1, min(int(count), 4))
    job = _json('/api/generate', {'generator': chosen['id'], 'prompt': prompt, 'size': size or (chosen['sizes'][0] if chosen['sizes'] else None), 'count': count})
    studio.access.record('generate.start', {'generator': chosen['id'], 'job': job.get('job_id')})
    return {'job': job.get('job_id'), 'generator': chosen, 'prompt': prompt}


def provenance(media: dict, generator: dict | None) -> dict:
    label = (generator or {}).get('label') or media.get('generator') or 'formvis'
    licence = (generator or {}).get('licence') or ''
    return {'source': 'formvis', 'title': (media.get('prompt') or '')[:120], 'creator': f'AI generated with {label} through formvis',
            'license': licence or 'Generated image: check the model or provider terms before publishing',
            'usage': media.get('notice') or media.get('licenceNotice') or '', 'prompt': (media.get('prompt') or '')[:500],
            'generator': media.get('generator') or (generator or {}).get('id', ''), 'created': datetime.now(timezone.utc).isoformat(timespec='seconds')}


def poll(studio, job: str) -> dict:
    """Follows a formvis job; when done, copies its pictures into FormWeb assets (once) and returns them."""
    studio.access.authorize('edit')
    if not isinstance(job, str) or not job.isalnum() or len(job) > 64:
        raise EngineError('Unknown generation job.', 404)
    done = studio.store.get_meta('generated:' + job)
    if done:
        return done
    state = _json('/api/jobs/' + job)
    status = state.get('status')
    if status in ('queued', 'running'):
        return {'job': job, 'status': status, 'progress': state.get('progress', 0), 'message': state.get('message', '')}
    if status != 'done':
        raise EngineError(f'formvis could not generate: {state.get("error") or status}', 502)
    try:
        catalogue = {g['id']: g for g in generators(studio)['generators']}
    except EngineError:
        catalogue = {}
    assets = []
    for media in (state.get('result') or {}).get('media', []):
        raw, headers = _call(media['url'], timeout=30.0)
        mime = {key.lower(): value for key, value in headers.items()}.get('content-type', 'image/png').split(';')[0]
        stored = ingest(raw, mime if mime in ('image/png', 'image/jpeg', 'image/webp') else 'application/octet-stream', (media.get('prompt') or 'generated')[:60] + '.png',
                        provenance(media, catalogue.get(media.get('generator'))))
        own_asset(studio, stored['id'])
        assets.append(stored)
        try:
            urllib.request.urlopen(urllib.request.Request(FORMVIS_URL + media['url'], method='DELETE'), timeout=5).read()  # formvis forgets its copy
        except (urllib.error.URLError, OSError):
            pass
    result = {'job': job, 'status': 'done', 'assets': assets, 'note': 'Saved as project assets with the prompt, generator and licence. Check the model or provider terms before publishing.'}
    studio.store.set_meta('generated:' + job, result)
    studio.access.record('generate.done', {'job': job, 'assets': [a['id'] for a in assets]})
    return result


async def wait(studio, job: str, seconds: float = 90.0) -> dict:
    """Polls on the service's own loop (the store is not shared across threads), yielding between checks."""
    import asyncio

    deadline = time.monotonic() + seconds
    while True:
        result = poll(studio, job)
        if result['status'] == 'done' or time.monotonic() > deadline:
            return result
        await asyncio.sleep(1.0)


async def insert_asset(studio, asset: dict, alt: str, parent: str | None = None) -> dict:
    """Adds a generated picture as an image element (agents; the editor inserts through its own Insert path)."""
    state = await studio.state()
    target = parent or state['site']['pages'][0]['root']
    if target not in state['site']['nodes']:
        raise EngineError('Unknown parent element. Read formweb://site/tree for element IDs.', 404)
    node = {'tag': 'img', 'name': (alt or 'Generated image')[:80], 'attrs': {'src': asset['url'], 'alt': alt[:300]}, 'styles': {'display': 'block', 'max-width': '100%', 'height': 'auto'}}
    result = await studio.mutate('exec', {'command': 'node.add', 'params': {'parent': target, 'node': node}})
    return {'node': result['site']['nodes'][target]['children'][-1], 'state': result}


# Edit in formvis ---------------------------------------------------------------------------------------------------
def _formvis_tool(name: str, arguments: dict, timeout: float = 120.0) -> dict:
    body = {'jsonrpc': '2.0', 'id': 1, 'method': 'tools/call', 'params': {'name': name, 'arguments': arguments}}
    reply = _json('/mcp', body, timeout=timeout)
    if 'error' in reply:
        raise EngineError(f'formvis: {reply["error"].get("message", "the request failed")}', 502)
    result = reply.get('result') or {}
    text = ' '.join(part.get('text', '') for part in result.get('content', []) if isinstance(part, dict))
    if result.get('isError'):
        raise EngineError(f'formvis: {text or "the window refused the request"}', 409)
    return {'text': text, 'data': result.get('structuredContent') or {}}


def _image_node(state: dict, node_id: str) -> tuple[dict, str]:
    node = state['site']['nodes'].get(node_id) if isinstance(node_id, str) else None
    match = ASSET_REF.search(((node or {}).get('attrs') or {}).get('src', '')) if node and node.get('tag') == 'img' else None
    if not match:
        raise EngineError('Choose an image element with an uploaded or generated picture.', 404)
    return node, match.group(1)


async def send_to_formvis(studio, node_id: str) -> dict:
    studio.access.authorize('edit')
    node, asset = _image_node(await studio.state(), node_id)
    if asset not in visible_assets(studio) or asset.endswith('.svg'):
        raise EngineError('This picture cannot be opened in formvis (icons are vectors; edit their colour in the stock library).', 422)
    folder = DATA_DIR / 'handoff'
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / asset
    path.write_bytes(asset_path(asset).read_bytes())
    result = _formvis_tool('open_file', {'path': str(path.resolve())})
    studio.access.record('formvis.send', {'node': node_id, 'asset': asset})
    return {'node': node_id, 'asset': asset, 'message': f'Opened "{node.get("name") or asset}" in formvis. Edit it there, then use Update from formvis to bring it back.', 'formvis': result['text']}


async def update_from_formvis(studio, node_id: str) -> dict:
    studio.access.authorize('edit')
    state = await studio.state()
    node, asset = _image_node(state, node_id)
    folder = DATA_DIR / 'handoff'
    folder.mkdir(parents=True, exist_ok=True)
    out = folder / f'{node_id[:60]}-{int(time.time())}.png'
    _formvis_tool('export_image', {'path': str(out.resolve())})
    if not out.is_file():
        raise EngineError('formvis did not write the picture. Is the edited document the one shown in formvis?', 502)
    metadata_path = asset_path(asset).with_name(asset + '.json')
    credit = (json.loads(metadata_path.read_text(encoding='utf-8')) if metadata_path.is_file() else {}).get('license') or {}
    credit = {**credit, 'editedIn': f'formvis, {datetime.now(timezone.utc).isoformat(timespec="seconds")}'}
    stored = ingest(out.read_bytes(), 'image/png', (node.get('name') or 'image') + ' (formvis edit).png', credit)
    out.unlink(missing_ok=True)
    own_asset(studio, stored['id'])
    result = await studio.mutate('exec', {'command': 'node.update', 'params': {'id': node_id, 'patch': {'attrs': {'src': stored['url']}}}})
    studio.access.record('formvis.update', {'node': node_id, 'asset': stored['id']})
    return {'node': node_id, 'asset': stored, 'state': result, 'message': 'Updated from formvis as one undo step; the earlier picture is kept and Undo brings it back.'}
